import { describe, expect, it } from "vitest";
import { normalizePhone } from "./phone";

describe("normalizePhone", () => {
  it.each([
    ["0912345678", "+84912345678"],
    ["+84912345678", "+84912345678"],
    ["84912345678", "+84912345678"],
    ["0084912345678", "+84912345678"],
    ["091 234 5678", "+84912345678"],
    ["091.234.5678", "+84912345678"],
    ["091-234-5678", "+84912345678"],
    ["+84 (91) 234 5678", "+84912345678"],
    ["  0912345678\n", "+84912345678"],
    ["0345678901", "+84345678901"],
    ["0567890123", "+84567890123"],
    ["0778901234", "+84778901234"],
    ["0889012345", "+84889012345"],
    ["０９１２３４５６７８", "+84912345678"],
    ["02838123456", "+842838123456"], // bàn HCM
    ["(028) 3812 3456", "+842838123456"],
    ["028.3812.3456", "+842838123456"],
    ["02412345678", "+842412345678"], // bàn HN
    ["02363123456", "+842363123456"], // bàn tỉnh (Đà Nẵng, 0236)
    ["+84 28 3812 3456", "+842838123456"],
    ["842838123456", "+842838123456"],
  ])("chấp nhận %j -> %j", (input, expected) => {
    expect(normalizePhone(input)).toBe(expected);
  });

  it.each([
    [""],
    ["   "],
    ["abc"],
    ["091234567"], // thiếu số
    ["09123456789"], // thừa số
    ["0212345678"], // cố định thiếu 1 số
    ["028381234567"], // cố định thừa số
    ["+84 028 3812 3456"], // thừa số 0 sau +84
    ["0112345678"], // đầu số 01 không tồn tại
    ["+1 202 555 0123"], // không phải VN
    ["+849123456789"],
    ["0912a45678"],
    ["0912345678 ext 5"],
    ["+84 0912345678"], // vừa +84 vừa số 0 đầu
    ["84-0912345678"],
    ["📞0912345678"],
    ["0".repeat(50)],
  ])("từ chối %j", (input) => {
    expect(normalizePhone(input)).toBeNull();
  });

  it("idempotent trên kết quả đã chuẩn hoá", () => {
    const once = normalizePhone("091 234 5678");
    expect(once && normalizePhone(once)).toBe(once);
  });
});
